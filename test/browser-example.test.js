// Drive the shipped page and its real SDK, with an independent Arrow wire encoder.
import assert from 'node:assert/strict';
import { test } from 'node:test';
import { createServer } from 'node:http';
import { once } from 'node:events';
import { chromium, firefox, webkit } from 'playwright';
import { tableFromArrays, tableToIPC } from 'apache-arrow';
import { serveExample } from '../examples/serve.mjs';

const token = 'a'.repeat(64);
const encode = values => Buffer.from(tableToIPC(tableFromArrays({ value: values }), 'stream')).toString('base64');
const schema = Buffer.from(tableToIPC(tableFromArrays({ value: [11, null, 11] }).slice(0, 0), 'stream')).toString('base64');
const frame = (kind, data, id) => `event: ${kind}\n${id ? `id: ${id}\n` : ''}data: ${data}\n\n`;
for (const [name, engine] of Object.entries({ chromium, firefox, webkit })) {
  test(`${name}: shipped demo stages, commits, resumes, refreshes and fails closed`, { timeout: 30000 }, async t => {
    const requests = [], closed = [], closing = []; let current;
    const server = createServer((req, res) => {
      if (req.url !== '/stream/v2') return serveExample(req, res);
      requests.push({ url: req.url, authorization: req.headers.authorization, cursor: req.headers['last-event-id'] });
      const index = requests.length; closing.push(new Promise(resolve => res.on('close', () => { closed.push(index); resolve(); })));
      res.writeHead(200, { 'content-type': 'text/event-stream', 'x-boilstream-sse-version': '2' });
      current = res;
      res.write(frame('schema', schema, req.headers['last-event-id']));
      if (!req.headers['last-event-id']) res.write(frame('snapshot', encode([11, null, 11])));
    });
    server.listen(0, '127.0.0.1'); await once(server, 'listening');
    t.after(async () => { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); });
    const browser = await engine.launch(); t.after(() => browser.close());
    const page = await browser.newPage(); page.setDefaultTimeout(5000); const errors = [], urls = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => urls.push(request.url()));
    const origin = `http://127.0.0.1:${server.address().port}`;
    await page.goto(origin);
    await page.locator('#endpoint').fill(`${origin}/stream/v2`);
    await page.locator('#token').fill(token);
    await page.locator('#start').click();
    await page.waitForFunction(() => document.querySelector('#status').textContent === 'staging snapshot');
    assert.equal(await page.locator('#rows').textContent(), '0');
    assert.equal(await page.locator('#cursor').textContent(), 'none');
    current.write(frame('snapshot-complete', '{}', 'r1.base') + frame('batch', encode([23]), 'r1.live'));
    await page.waitForFunction(() => document.querySelector('#rows').textContent === '4');
    assert.deepEqual(JSON.parse(await page.locator('#preview').textContent()), [{value:11},{value:null},{value:11},{value:23}]);
    assert.equal(await page.locator('#cursor').textContent(), 'r1.live');
    if (process.env.SSE_EXAMPLE_SCREENSHOT && name === 'chromium') await page.screenshot({ path: process.env.SSE_EXAMPLE_SCREENSHOT, fullPage: true });
    await page.locator('#stop').click();
    await page.waitForFunction(() => document.querySelector('#status').textContent === 'stopped');
    assert.equal(await page.locator('#rows').textContent(), '4');
    await page.locator('#token').fill(token); await page.locator('#resume').click();
    await page.waitForFunction(() => document.querySelector('#status').textContent === 'live');
    assert.equal(requests[1].cursor, 'r1.live');
    current.write(frame('batch', encode([42]), 'r1.next'));
    await page.waitForFunction(() => document.querySelector('#rows').textContent === '5');
    current.end(frame('refresh-required', '{"reason":"refresh_required"}'));
    await page.waitForFunction(() => document.querySelector('#status').textContent.startsWith('refresh required'));
    assert.equal(await page.locator('#rows').textContent(), '0');
    assert.equal(await page.locator('#cursor').textContent(), 'none');
    assert.ok(await page.locator('#resume').isDisabled());
    await page.locator('#token').fill(token); await page.locator('#start').click();
    await page.waitForFunction(() => document.querySelector('#status').textContent === 'staging snapshot');
    current.end(frame('snapshot', 'not-arrow'));
    await page.waitForFunction(() => document.querySelector('#status').textContent.startsWith('refresh required'));
    assert.equal(await page.locator('#rows').textContent(), '0');
    assert.equal(requests.length, 3, 'terminal failures must not reconnect silently');
    await page.locator('#token').fill(token); await page.locator('#start').click();
    await page.waitForFunction(() => document.querySelector('#status').textContent === 'staging snapshot');
    current.end(frame('snapshot', encode(Array(10001).fill(1))));
    await page.waitForFunction(() => document.querySelector('#status').textContent.startsWith('refresh required'));
    assert.equal(await page.locator('#rows').textContent(), '0', 'row limit must invalidate provisional state');
    assert.equal(await page.locator('#cursor').textContent(), 'none');
    assert.equal(requests.length, 4);
    assert.ok(requests.every(r => r.url === '/stream/v2' && r.authorization === `Bearer ${token}`));
    assert.ok(urls.every(url => url.startsWith(origin) && !url.includes(token)), 'no CDN or token URL');
    assert.equal(await page.locator('#token').inputValue(), '');
    assert.deepEqual(await page.evaluate(() => [localStorage.length, sessionStorage.length]), [0,0]);
    assert.deepEqual(errors, []);
    await Promise.all(closing);
    assert.ok([1,2,3,4].every(index => closed.includes(index)), 'all stream sockets must close');
  });
}
